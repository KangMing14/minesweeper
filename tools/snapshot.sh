#!/usr/bin/env bash
# Makes a zip of the repository to attach to a Claude conversation.
#
# Usage (run from anywhere inside the repo, in Git Bash on Windows or any shell on macOS/Linux):
#   tools/snapshot.sh                      # whole repo (files git knows about, minus ignored files)
#   tools/snapshot.sh packages/engine      # root-level files + only the listed folders
#   tools/snapshot.sh packages/engine packages/protocol docs/adr
#
# Optional flags (off by default; with no flag the zip is exactly what it always was). Flags can go
# before or after the folder names:
#   --git-state   also writes GIT_STATE.txt at the zip root: HEAD, recent first-parent history, tags,
#                 the number of merge commits (history should be linear), `git status`, the remote
#                 URL without credentials, and, when the GitHub CLI `gh` is installed and signed in,
#                 the branch protection of main and its last five CI runs. This is what a milestone
#                 review needs. Run `git fetch` first so origin/main is current.
#   --with-git    also includes the .git folder (history, tags, objects), except .git/config and
#                 .git/hooks, which can hold credentials or local scripts. Only for a deep history
#                 check; --git-state is enough for a milestone review. The zip gets larger.
#   -h, --help    show this text
#
# What it includes: files tracked by git plus new files that are not ignored.
# What it leaves out: everything in .gitignore (node_modules, dist, coverage, ...),
# the .git folder (unless --with-git), and any .env file except .env.example.
# The zip is written to ../snapshots/ (outside the repo, so it is never committed).
#
# Zip tool: uses the first one found of zip, 7z/7za/7zz, python3/python, PowerShell.
# Git Bash on Windows has none of the first one, so the others are fallbacks.
set -euo pipefail

git_state=0
with_git=0
paths=()
for arg in "$@"; do
  case "$arg" in
    --git-state) git_state=1 ;;
    --with-git) with_git=1 ;;
    -h|--help) sed -n '2,/^set -euo/p' "$0" | sed '$d' | sed 's/^# \{0,1\}//'; exit 0 ;;
    -*) echo "Unknown option: $arg (see --help)" >&2; exit 2 ;;
    *) paths+=("$arg") ;;
  esac
done

cd "$(git rev-parse --show-toplevel)"
mkdir -p ../snapshots
stamp="$(date +%Y%m%d-%H%M)"
suffix=""
if [ "${#paths[@]}" -gt 0 ]; then suffix="-partial"; fi
if [ "$git_state" -eq 1 ]; then suffix="${suffix}-gitstate"; fi
if [ "$with_git" -eq 1 ]; then suffix="${suffix}-git"; fi
out="$(cd ../snapshots && pwd)/minesweeper-${stamp}${suffix}.zip"
rm -f "$out"

list_all() { git ls-files --cached --others --exclude-standard; }

if [ "${#paths[@]}" -eq 0 ]; then
  files="$(list_all)"
else
  files="$( { list_all | grep -v "/" || true
              for p in "${paths[@]}"; do git ls-files --cached --others --exclude-standard -- "$p"; done
            } | sort -u )"
fi

# Never include secrets: drop .env and .env.* but keep .env.example
files="$(printf "%s\n" "$files" | awk "!/(^|\/)\.env(\.|\$)/ || /\.env\.example\$/")"

if [ -z "$files" ]; then
  echo "No files matched." >&2
  exit 1
fi

list_file="$(mktemp)"
state_file="GIT_STATE.txt"   # written into the repo root only while the zip is made, then removed
trap 'rm -f "$list_file" "$state_file"' EXIT

# GIT_STATE.txt: facts about history and GitHub that a snapshot without .git cannot show. It never
# prints credentials: the remote URL is stripped of user info, and `gh` output has none.
write_git_state() {
  local remote slug
  remote="$(git remote get-url origin 2>/dev/null | sed -E 's#(https?://)[^/@]*@#\1#' || true)"
  slug="$(printf '%s' "$remote" | sed -E 's#^(https?://[^/]+/|git@[^:]+:|ssh://git@[^/]+/)##; s#\.git$##')"
  {
    echo "Generated by tools/snapshot.sh --git-state on $(date -u +%Y-%m-%dT%H:%M:%SZ)."
    echo "Run 'git fetch' before taking the snapshot, or origin/main below may be out of date."
    echo
    echo "== HEAD"
    echo "branch: $(git rev-parse --abbrev-ref HEAD 2>/dev/null || echo unknown)"
    echo "HEAD:        $(git rev-parse HEAD 2>/dev/null || echo unknown)"
    echo "origin/main: $(git rev-parse --verify -q origin/main || echo 'not found')"
    echo "remote: ${remote:-none}"
    echo
    echo "== first-parent history (newest first, 40)"
    git log --first-parent --decorate --format='%h %ad %s' --date=short -n 40 2>/dev/null || true
    echo
    echo "== merge commits reachable from HEAD (linear history expects 0)"
    git rev-list --merges --count HEAD 2>/dev/null || echo unknown
    echo
    echo "== tags (newest first)"
    git tag -l --sort=-creatordate --format='%(refname:short) %(objectname:short) %(creatordate:short)' 2>/dev/null || true
    echo
    echo "== working tree (git status --short, first 40 lines)"
    git status --short 2>/dev/null | head -40 || true
    echo
    echo "== GitHub: branch protection of main"
    if command -v gh >/dev/null 2>&1 && [ -n "$slug" ]; then
      gh api "repos/$slug/branches/main/protection" 2>&1 | head -80 || echo "gh could not read the protection (sign in with 'gh auth login' and check repo access)"
      echo
      echo "== GitHub: last five CI runs on main"
      gh run list --repo "$slug" --branch main --limit 5 2>&1 || true
    else
      echo "gh (GitHub CLI) is not installed or the remote is not a GitHub URL: protection and CI runs not captured."
      echo "Run 'tools/verify-t01.sh --remote OWNER/REPO' and 'gh run list --branch main --limit 3' by hand."
    fi
  } > "$state_file"
  files="$(printf '%s\n%s' "$files" "$state_file")"
}

# --with-git: the .git folder, minus config (may hold a token in a remote URL) and hooks.
add_git_folder() {
  if [ ! -d .git ]; then
    echo "--with-git: .git is not a folder here (a git worktree?); skipped." >&2
    return 0
  fi
  files="$(printf '%s\n%s' "$files" "$(find .git -type f ! -path '.git/config' ! -path '.git/hooks/*' ! -name '*.lock' | sort)")"
}

if [ "$git_state" -eq 1 ]; then write_git_state; fi
if [ "$with_git" -eq 1 ]; then add_git_folder; fi

# Tools that can zip a list of paths directly, keeping repo-relative paths.
zip_with_list() {
  if command -v zip >/dev/null 2>&1; then
    printf "%s\n" "$files" | zip -q "$out" -@
  elif command -v 7z >/dev/null 2>&1 || command -v 7za >/dev/null 2>&1 || command -v 7zz >/dev/null 2>&1; then
    local z; z="$(command -v 7z || command -v 7za || command -v 7zz)"
    printf "%s\n" "$files" > "$list_file"
    "$z" a -tzip -bd -bso0 "$out" "@$list_file"
  elif command -v python3 >/dev/null 2>&1 || command -v python >/dev/null 2>&1; then
    local py; py="$(command -v python3 || command -v python)"
    printf "%s\n" "$files" | "$py" -c "
import sys, zipfile
with zipfile.ZipFile(sys.argv[1], \"w\", zipfile.ZIP_DEFLATED) as z:
    for line in sys.stdin:
        p = line.rstrip(\"\r\n\")
        if p:
            z.write(p, p)
" "$out"
  else
    return 1
  fi
}

# Last resort: stage a copy of the files, then zip the folder with PowerShell.
zip_with_powershell() {
  local ps
  ps="$(command -v powershell.exe || command -v pwsh || true)"
  [ -n "$ps" ] || return 1
  local stage; stage="$(mktemp -d)"
  while IFS= read -r f; do
    [ -n "$f" ] || continue
    mkdir -p "$stage/$(dirname "$f")"
    cp "$f" "$stage/$f"
  done <<<"$files"
  local win_stage win_out
  win_stage="$(cygpath -w "$stage" 2>/dev/null || echo "$stage")"
  win_out="$(cygpath -w "$out" 2>/dev/null || echo "$out")"
  "$ps" -NoProfile -Command "Add-Type -AssemblyName System.IO.Compression.FileSystem; [System.IO.Compression.ZipFile]::CreateFromDirectory(\"$win_stage\", \"$win_out\")"
  rm -rf "$stage"
}

if ! zip_with_list; then
  zip_with_powershell || {
    echo "No zip tool found. Install one of: zip, 7-Zip, Python, or run from WSL (sudo apt install zip)." >&2
    exit 1
  }
fi

count="$(printf "%s\n" "$files" | wc -l | tr -d " ")"
size="$(du -h "$out" | cut -f1)"
echo "Wrote $out ($count files, $size)"
